"""Write provisional header samples into tests/fixtures/headers/provisional/.

These are made by the synthetic generator in each software's *expected* style. They are a
stand-in until real export samples are supplied, and show the format a real sample should
take (header lines plus about five rows). Run from the project folder:

    .venv/bin/python tests/make_provisional_fixtures.py
"""

from __future__ import annotations

from pathlib import Path

import yaml
from synthetic import make_model

from qaqc.schema import STRUCTURAL_LABELS

OUT = Path(__file__).parent / "fixtures" / "headers" / "provisional"
CASES = [
    ("datamine", "regular"),
    ("datamine", "sub_blocked"),
    ("isatis", "regular"),
    ("isatis", "percentage"),
    ("leapfrog", "regular"),
    ("leapfrog", "sub_blocked"),
]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    expected: dict[str, dict] = {}
    for style, kind in CASES:
        m = make_model(kind, style=style, rotation_deg=30.0, n_parents=(8, 8, 6))
        name = f"{style}_{kind}.csv"
        (OUT / name).write_text(m.header_sample(5), encoding="utf-8")
        cols = m.columns
        meta = {k.split(":", 1)[1]: v for k, v in cols.items() if k.startswith("meta:")}
        element_scoped = style in ("leapfrog", "isatis")
        elements = {
            "cu": {"primary": cols["cu"], "nn": cols["cu_nn"]},
            "au": {"primary": cols["au"], "nn": cols["au_nn"]},
        }
        if element_scoped and meta:
            elements["cu"]["metadata"] = meta
        if "meta_au:nsamples" in cols:
            elements["au"]["metadata"] = {"nsamples": cols["meta_au:nsamples"]}
        expected[name] = {
            "software": style,
            "structural": {k: v for k, v in cols.items() if k in STRUCTURAL_LABELS},
            "global_metadata": {} if element_scoped else meta,
            "elements": elements,
            "unmatched": [cols["lith"]],
        }
    header = (
        "# Expected column matches for the provisional header samples in this folder.\n"
        "# Generated by tests/make_provisional_fixtures.py from the synthetic generator.\n"
    )
    (OUT / "expected.yaml").write_text(
        header + yaml.safe_dump(expected, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    print(f"Wrote {len(CASES)} provisional samples to {OUT}")


if __name__ == "__main__":
    main()
